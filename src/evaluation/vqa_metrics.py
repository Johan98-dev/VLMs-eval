"""Answer extraction and metric computation for Stage 1 Closed-Ended & Binary/Yes-No VQA."""

import re
from typing import Any, Dict, List, Optional, Sequence


def extract_closed_vqa_choice(
    raw_output: str,
    options: Dict[str, str],
) -> Optional[str]:
    """Extract the predicted option letter ('A', 'B', 'C', 'D') from a model's raw response.

    Supports:
    - Leading or standalone option letters (e.g., 'B. Positive', 'Answer: C', '(A)')
    - Exact or substring match against option text (e.g., 'Invasive ductal carcinoma')
    - Binary Yes/No and Positive/Negative semantic mapping when options are binary.

    Args:
        raw_output: Raw text string generated by the VLM.
        options: Mapping of valid option keys ('A', 'B', ...) to option descriptions.

    Returns:
        Predicted option key ('A', 'B', 'C', or 'D') if matched, otherwise None.
    """
    if not raw_output or not raw_output.strip():
        return None

    text = raw_output.strip()
    valid_keys = [k.upper() for k in options.keys()]
    key_pattern = "|".join(re.escape(k) for k in valid_keys)

    # 1. Match explicit leading letter pattern: "A", "A.", "A)", "(A)", "Answer: A", "Option A"
    explicit_patterns = [
        rf"^\s*\(?({key_pattern})\)?(?:[\.\:\)\s]|$)",
        rf"(?:answer|option|choice)\s*(?:is|:)?\s*\(?({key_pattern})\)?(?:[\.\:\)\s]|$)",
    ]
    for pat in explicit_patterns:
        match = re.search(pat, text, flags=re.IGNORECASE)
        if match:
            cand = match.group(1).upper()
            if cand in valid_keys:
                return cand

    # 2. Match option text (longest option text first to avoid partial prefix collisions)
    lower_text = text.lower()
    sorted_opts = sorted(
        [(k.upper(), v.strip()) for k, v in options.items() if v.strip()],
        key=lambda item: len(item[1]),
        reverse=True,
    )
    for opt_key, opt_val in sorted_opts:
        if opt_val.lower() in lower_text:
            return opt_key

    # 3. Binary Yes/No <-> Positive/Negative semantic equivalence fallback
    if len(valid_keys) == 2:
        opt_lower_map = {v.strip().lower(): k.upper() for k, v in options.items()}
        if {"yes", "no"} == set(opt_lower_map.keys()):
            if re.search(r"\b(yes|positive|present)\b", lower_text):
                return opt_lower_map["yes"]
            if re.search(r"\b(no|negative|absent)\b", lower_text):
                return opt_lower_map["no"]
        if {"positive", "negative"} == set(opt_lower_map.keys()):
            if re.search(r"\b(positive|yes)\b", lower_text):
                return opt_lower_map["positive"]
            if re.search(r"\b(negative|no)\b", lower_text):
                return opt_lower_map["negative"]

    # 4. Standalone letter fallback anywhere in a short response
    standalone = re.findall(rf"\b({key_pattern})\b", text)
    if len(standalone) == 1 and standalone[0].upper() in valid_keys:
        return standalone[0].upper()

    return None


def compute_vqa_metrics(records: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """Compute overall, per-question-type, and per-task accuracy metrics for closed-ended VQA.

    Args:
        records: List of evaluated prediction records.

    Returns:
        Dictionary with aggregated accuracy statistics and breakdowns.
    """
    total = len(records)
    if total == 0:
        return {"total_samples": 0, "overall_accuracy": 0.0}

    correct = sum(1 for r in records if r.get("is_correct", False))
    unparsed = sum(1 for r in records if r.get("predicted_choice") is None)

    by_qtype: Dict[str, Dict[str, Any]] = {}
    by_task: Dict[str, Dict[str, Any]] = {}
    by_cohort: Dict[str, Dict[str, Any]] = {}

    for rec in records:
        is_corr = bool(rec.get("is_correct", False))
        for group_dict, key in (
            (by_qtype, str(rec.get("question_type", "unknown"))),
            (by_task, str(rec.get("task", "unknown"))),
            (by_cohort, str(rec.get("cohort", "unknown"))),
        ):
            entry = group_dict.setdefault(key, {"correct": 0, "total": 0, "accuracy": 0.0})
            entry["total"] += 1
            if is_corr:
                entry["correct"] += 1

    for group_dict in (by_qtype, by_task, by_cohort):
        for entry in group_dict.values():
            entry["accuracy"] = round(entry["correct"] / max(1, entry["total"]), 4)

    return {
        "total_samples": total,
        "correct_samples": correct,
        "unparsed_samples": unparsed,
        "overall_accuracy": round(correct / total, 4),
        "by_question_type": by_qtype,
        "by_task": by_task,
        "by_cohort": by_cohort,
    }
